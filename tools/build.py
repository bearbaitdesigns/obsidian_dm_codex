#!/usr/bin/env python3
"""
Build DM Codex.

    python3 tools/build.py                       # writes main.js (plugin with the content pack embedded)
    python3 tools/build.py --vault "out/DM Vault" --statblocks ../obsidian_dm_statblocks --zip
                                                 # also assembles the full starter vault (+ zip)
    python3 tools/build.py --update-zip out/DM-Vault-Update.zip --statblocks ../obsidian_dm_statblocks
                                                 # plugins-only update zip (no notes, no settings)

The content pack = the reference notes generated by content/gen_*.py (rules, spells, armory catalog,
SRD bestiary, templates, DM tools). It is embedded in main.js so BRAT / the community store, which only
download main.js + manifest.json + styles.css, deliver it too. The example campaign is generated into
the starter vault only and is never part of the pack.
"""
import argparse, json, os, re, shutil, struct, subprocess, sys, tempfile, zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GENERATORS = ['gen_core', 'gen_rules', 'gen_world', 'gen_armory', 'gen_spells']
PLUGIN_FILES = ['main.js', 'manifest.json', 'styles.css']


def norm(s):
    s = s.replace('\r\n', '\n')
    s = re.sub(r'[ \t]+$', '', s, flags=re.M)
    return re.sub(r'\s+$', '', s)


def content_hash(s):
    """FNV-1a over UTF-16 code units — identical to contentHash() in src/main.js."""
    h = 0x811c9dc5
    for (u,) in struct.iter_unpack('<H', norm(s).encode('utf-16-le')):
        h = ((h ^ u) * 0x01000193) & 0xffffffff
    return f'{h:08x}'


def is_managed(rel, text):
    """Reference notes shipped (and safely updated) by the plugin. Campaign/example notes are excluded."""
    if rel.startswith(('Rules 2024/', 'Templates/', 'DM Tools/')):
        return True
    if rel in ('Home.md', 'How to Use This Vault.md', 'Armory/Armory Index.md', 'Bestiary/Bestiary Index.md'):
        return True
    if rel.startswith('Armory/') and '\nbase:' not in text and not rel.startswith('Armory/Magic Items/'):
        return True
    if rel.startswith('Bestiary/') and '\nsource: SRD 5.2' in text:
        return True
    return False


def generate_vault(vault):
    os.makedirs(vault, exist_ok=True)
    for g in GENERATORS:
        subprocess.run([sys.executable, '-I', os.path.join(ROOT, 'content', g + '.py'), vault], check=True, stdout=subprocess.DEVNULL)


def collect_pack(vault, version):
    files = {}
    for root, _, fs in os.walk(vault):
        if os.sep + '.obsidian' in root:
            continue
        for fn in fs:
            if fn.endswith('.md'):
                p = os.path.join(root, fn)
                rel = os.path.relpath(p, vault).replace(os.sep, '/')
                text = open(p, encoding='utf-8').read()
                if is_managed(rel, text):
                    files[rel] = text
    snippet = open(os.path.join(vault, '.obsidian', 'snippets', 'dm-vault-callouts.css'), encoding='utf-8').read()
    return {'version': version, 'files': dict(sorted(files.items())), 'snippets': {'dm-vault-callouts': snippet}}


def build_main_js(pack):
    src = open(os.path.join(ROOT, 'src', 'main.js'), encoding='utf-8').read()
    embedded = 'const EMBEDDED_CONTENT_PACK = ' + json.dumps(pack, ensure_ascii=False).replace('\u2028', '\\u2028').replace('\u2029', '\\u2029') + ';'
    out, n = re.subn(r'/\* @@CONTENT_PACK_START@@ \*/.*?/\* @@CONTENT_PACK_END@@ \*/',
                     lambda _: '/* @@CONTENT_PACK_START@@ */\n' + embedded + '\n/* @@CONTENT_PACK_END@@ */', src, flags=re.S)
    if n != 1:
        sys.exit('content pack markers not found in src/main.js')
    open(os.path.join(ROOT, 'main.js'), 'w', encoding='utf-8').write(out)
    return len(out)


def install_plugins(vault, pack, statblocks):
    cfg = os.path.join(vault, '.obsidian', 'plugins')
    codex = os.path.join(cfg, 'dm-codex'); os.makedirs(codex, exist_ok=True)
    for f in PLUGIN_FILES:
        shutil.copy(os.path.join(ROOT, f), codex)
    data = {'campaignName': 'The Ashen Crown', 'contentVersion': pack['version'],
            'managed': {k: content_hash(v) for k, v in pack['files'].items()}}
    json.dump(data, open(os.path.join(codex, 'data.json'), 'w'), indent=1)
    if statblocks:
        sb = os.path.join(cfg, 'dm-statblocks'); os.makedirs(sb, exist_ok=True)
        for f in PLUGIN_FILES:
            shutil.copy(os.path.join(statblocks, f), sb)


def zip_dir(src, dest, arc_root):
    with zipfile.ZipFile(dest, 'w', zipfile.ZIP_DEFLATED) as z:
        for root, _, fs in os.walk(src):
            for fn in fs:
                p = os.path.join(root, fn)
                z.write(p, os.path.join(arc_root, os.path.relpath(p, src)))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--vault', help='also write the full starter vault here')
    ap.add_argument('--statblocks', help='path to the obsidian_dm_statblocks repo (for --vault / --update-zip)')
    ap.add_argument('--zip', action='store_true', help='zip the starter vault next to it')
    ap.add_argument('--update-zip', help='write a plugins-only update zip here')
    a = ap.parse_args()
    version = json.load(open(os.path.join(ROOT, 'manifest.json')))['version']

    tmp = None
    vault = a.vault
    if not vault:
        tmp = tempfile.mkdtemp(); vault = os.path.join(tmp, 'DM Vault')
    elif os.path.exists(vault):
        shutil.rmtree(vault)
    generate_vault(vault)
    pack = collect_pack(vault, version)
    size = build_main_js(pack)
    print(f'main.js built: v{version}, {len(pack["files"])} reference notes embedded, {size // 1024} KB')

    if a.vault:
        install_plugins(vault, pack, a.statblocks)
        if a.zip:
            dest = os.path.join(os.path.dirname(os.path.abspath(vault)), 'DM-Vault.zip')
            zip_dir(vault, dest, os.path.basename(vault)); print('starter vault zip:', dest)
    if a.update_zip:
        with zipfile.ZipFile(a.update_zip, 'w', zipfile.ZIP_DEFLATED) as z:
            for f in PLUGIN_FILES:
                z.write(os.path.join(ROOT, f), 'dm-codex/' + f)
            if a.statblocks:
                for f in PLUGIN_FILES:
                    z.write(os.path.join(a.statblocks, f), 'dm-statblocks/' + f)
            z.writestr('HOW TO UPDATE.txt', UPDATE_README.format(version=version))
        print('update zip:', a.update_zip)
    if tmp:
        shutil.rmtree(tmp)


UPDATE_README = """DM Vault update v{version}
==========================

This zip contains ONLY the two plugins. No notes, no settings. Your campaign is not touched.

1. In Obsidian open Settings -> Community plugins and click the folder icon next to
   "Installed plugins". That opens your vault's .obsidian/plugins folder.
2. Copy the "dm-codex" and "dm-statblocks" folders from this zip into it, replacing the files.
   (On a Mac, Finder's "Replace" swaps the whole folder. That's fine: both plugins back up
   their settings and restore them automatically.)
3. In Obsidian, turn both plugins off and on again (or restart Obsidian).
4. Click the "content update available" notice, or the banner on the DM Codex dashboard, or run
   "DM Codex: Update vault content". You'll see a plan first:
     - new reference notes are added,
     - reference notes you haven't edited are refreshed,
     - notes you HAVE edited are kept (you can view or take the new version, one by one),
     - notes you deleted are not re-added,
     - campaign notes (sessions, party, NPCs, places, quests, ideas, encounters, your own
       monsters and items) are never touched.

Tip: back up your vault folder first, just in case.
"""

if __name__ == '__main__':
    main()
